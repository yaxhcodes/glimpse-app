/// Country names and first-level division vocabulary for grouping places.
library;

/// Whether [name] names a whole country or continent rather than a place in
/// one ("Kyrgyzstan", "USA", "Southeast Asia"). Travel reels name the country
/// they are about; that is the area, not a pin.
bool isCountryOrContinentName(String name) {
  final key = _key(name);
  return key.isNotEmpty &&
      (_countryNames.contains(key) || _continentNames.contains(key));
}

/// Whether [name] names a first-level division by its title ("Osaka
/// Prefecture", "Issyk-Kul Region", "Chuy Oblast"): an area, not a pin.
bool isNamedRegion(String name) => RegExp(
  r'\s(prefecture|province|region|oblast|governorate|voivodeship|canton)$',
  caseSensitive: false,
).hasMatch(name.trim());

/// Whether [value] has letters but none in Latin script. The app asks the
/// geocoder for English; an answer in Cyrillic or Kana means it had no
/// English name, and it would read as noise beside English labels.
bool isNonLatinName(String value) {
  final letters = RegExp(r'\p{L}', unicode: true).allMatches(value);
  if (letters.isEmpty) return false;
  return !RegExp(r'[A-Za-zÀ-ɏ]').hasMatch(value);
}

/// "4 prefectures", "1 state": what [country] calls its first-level
/// divisions, in English. Null when the country has no known term; callers
/// fall back to the localized generic "regions".
String? englishRegionCount(String? country, int count) {
  final plural = _regionTerms[_key(country ?? '')];
  if (plural == null) return null;
  final term = count == 1 ? _singular(plural) : plural;
  return '$count ${term.toLowerCase()}';
}

String _singular(String plural) => switch (plural) {
  'Counties' => 'County',
  'Countries' => 'Country',
  'Communities' => 'Community',
  _ => plural.substring(0, plural.length - 1),
};

/// Drops the division word a geocoder appends ("Kyoto Prefecture",
/// "Sichuan Province", "Issyk-Kul Region") so chips stay short. Leaves names
/// where the word is the whole name or part of it ("New York State" stays
/// intact only when stripping would leave nothing).
String shortRegionName(String region) {
  final trimmed = region.replaceAll(RegExp(r'\s+'), ' ').trim();
  final stripped = trimmed
      .replaceFirst(
        RegExp(
          r'\s+(prefecture|province|state|region|oblast|governorate|'
          r'department|county|district|emirate|canton|voivodeship)$',
          caseSensitive: false,
        ),
        '',
      )
      .trim();
  return stripped.isEmpty ? trimmed : stripped;
}

String _key(String value) => value
    .toLowerCase()
    .replaceAll(RegExp(r'[’`]'), "'")
    .replaceAll(RegExp(r'[.]'), '')
    .replaceAll(RegExp(r'\s+'), ' ')
    .trim()
    .replaceFirst(RegExp(r'^the '), '');

